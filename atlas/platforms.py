@dataclass(frozen=True, slots=True)
class PlatformTranslation:
    """The table's answer for one or more pairs: per pair, and their intersection (#784 D7–D9)."""

    table_version: int
    """The table's own version — one of the two things stability is promised for (#784 D12)."""
    source_versions: tuple[PlatformSourceVersion, ...]
    """The pinned version of every project each source's column is read from, one entry per
    source and project (#784 D11, D42).
    """
    pairs: tuple[PlatformPairAnswer, ...]
    """One answer per asked pair, in the order asked."""
    intersection_status: PlatformIntersectionStatus
    """``agreed``, ``conflict`` or ``unknown``, one of :data:`PLATFORM_INTERSECTION_STATUSES`."""
    intersection: tuple[PlatformSourceKeys, ...]
    """Every source's keys for the systems all known pairs share; empty unless ``agreed``."""
    conflict: tuple[PlatformPairAnswer, ...]
    """The known pairs that share no system, when ``conflict``; empty otherwise."""
    caveats: tuple[Caveat, ...]
    """What the answer cannot settle: why each unknown pair is unknown (one caveat per pair), a stated
    source version the table does not hold, a version a bare folder pair could not apply, and pairs that
    share a system only through different parts or overlaps of it (``platform-parts-unestablished``).
    """

    def __post_init__(self) -> None:
        status = self.intersection_status
        if status not in PLATFORM_INTERSECTION_STATUSES:
            raise ValueError(
                f"PlatformTranslation: intersection_status {status!r} is not one of {PLATFORM_INTERSECTION_STATUSES}"
            )
        if not self.pairs:
            raise ValueError("PlatformTranslation: a translation answers at least one pair")
        if (status == INTERSECTION_AGREED) != bool(self.intersection):
            raise ValueError("PlatformTranslation: the intersection lists sources exactly when it is agreed")
        if (status == INTERSECTION_CONFLICT) != bool(self.conflict):
            raise ValueError("PlatformTranslation: conflict names pairs exactly when the intersection is a conflict")
        if (status == INTERSECTION_UNKNOWN) != all(p.status == PAIR_UNKNOWN for p in self.pairs):
            raise ValueError("PlatformTranslation: the intersection is unknown exactly when every pair is")
        known = tuple(p for p in self.pairs if p.status == PAIR_KNOWN)
        if self.conflict and (self.conflict != known or len(known) < 2):
            raise ValueError("PlatformTranslation: a conflict names every known pair, and there are at least two")
        if self.intersection and not _any_keys(self.intersection):
            raise ValueError("PlatformTranslation: an agreed intersection has a key in some source")
        self._check_caveats()

    def _check_caveats(self) -> None:
        """The caveats say what the pairs and the intersection are.

        Three checks: one caveat per unknown pair, each with its cause; a source-unknown caveat names a source its
        own list of sources lacks; and pairs meeting through parts or overlaps are stated at most once, only on an
        agreed intersection, with only sources and keys as data, naming at least two known pairs in pair order.
        """
        stated = [(c.data.get("source"), c.data.get("key")) for c in self.caveats if c.code in UNKNOWN_PAIR_CODES]
        if stated != [(p.source, p.key) for p in self.pairs if p.status == PAIR_UNKNOWN]:
            raise ValueError("PlatformTranslation: every unknown pair, and nothing else, states why in one caveat")
        if any(
            c.code == CAVEAT_PLATFORM_SOURCE_UNKNOWN and isinstance(source := c.data["source"], str)
            and source in c.data["sources"]
            for c in self.caveats
        ):
            raise ValueError(
                "PlatformTranslation: platform-source-unknown names a source its own list of sources lacks"
            )
        parts = [c for c in self.caveats if c.code == CAVEAT_PLATFORM_PARTS_UNESTABLISHED]
        if len(parts) > 1 or (parts and self.intersection_status != INTERSECTION_AGREED):
            raise ValueError(
                "PlatformTranslation: pairs meet through parts or overlaps at most once, and only on an agreed "
                "intersection"
            )
        if parts and set(parts[0].data) != {"sources", "keys"}:
            raise ValueError(
                "PlatformTranslation: platform-parts-unestablished carries sources and keys, and nothing else"
            )
        if parts and not self._names_known_pairs(parts[0]):
            raise ValueError(
                "PlatformTranslation: platform-parts-unestablished names at least two known pairs, in pair order"
            )

    def _names_known_pairs(self, caveat: Caveat) -> bool:
        """The caveat's two lists pair up into at least two known pairs, each named in pair order."""
        sources, keys = caveat.data["sources"], caveat.data["keys"]
        if len(sources) != len(keys) or len(sources) < 2:
            return False
        rest = iter((p.source, p.key) for p in self.pairs if p.status == PAIR_KNOWN)
        return all(any(named == known for known in rest) for named in zip(sources, keys, strict=True))


def _any_keys(sources: tuple[PlatformSourceKeys, ...]) -> bool:
    return any(s.status == KEYS_FOUND for s in sources)


# How much of a row a placement covers: all of it (every generated placement,
# and a map that states no relation), part of it (a map's narrowMatch), or an
# overlap that may also reach outside it (a map's relatedMatch). Set once, at
# load; the relations an answer states are computed from it.
_Coverage = Literal["whole", "part", "overlap"]
_WHOLE: _Coverage = "whole"
_PART: _Coverage = "part"
_OVERLAP: _Coverage = "overlap"
_MAPPED_COVERAGE: dict[str | None, _Coverage] = {None: _WHOLE, NARROW_MATCH: _PART, RELATED_MATCH: _OVERLAP}


@dataclass(frozen=True, slots=True)
class _Placement:
    coverage: _Coverage
    citations: tuple[str, ...]


_SEPARATOR = "; "


def _fragments_once(citations: Iterable[str]) -> tuple[str, ...]:
    """*citations* with every ``; ``-separated fragment kept once, in order (#784 D38).

    A citation whose fragments all came earlier is dropped; one that repeats
    some keeps the fragments that are new, so no line is named twice.
    """
    seen: set[str] = set()
    kept: list[str] = []
    for citation in citations:
        new = [f for f in citation.split(_SEPARATOR) if f not in seen]
        seen.update(new)
        if new:
            kept.append(_SEPARATOR.join(new))
    return tuple(kept)


# One project a column is read from: its name as SOURCES.md has it, and its pinned version (#784 D42).
_Pin = tuple[str, str]


@dataclass(frozen=True, slots=True)
class PlatformTable:
    """The loaded table with the overrides applied — rows internal, keys per source.

    ``placements`` maps ``(source, key)`` to the rows that key covers. Row names
    are the generator's working names and stay inside this module.
    """

    table_version: int
    sources: Mapping[str, tuple[_Pin, ...]]
    keys: Mapping[str, frozenset[str]]
    kinds: Mapping[str, str]
    kind_conflicts: Mapping[str, tuple[str, ...]]
    subset_of: Mapping[str, str]
    excluded: Mapping[tuple[str, str], str]
    placements: Mapping[tuple[str, str], Mapping[str, _Placement]]
    by_row: Mapping[str, Mapping[str, tuple[str, ...]]]


def _expect_str(value: Any, where: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{where}: expected a non-empty string, got {value!r}")
    return value


def _expect_dict(value: Any, where: str, fields: Iterable[str]) -> dict[str, Any]:
    wanted = set(fields)
    if not isinstance(value, dict) or set(value) != wanted:
        raise ValueError(f"{where}: expected exactly {sorted(wanted)}, got {value!r}")
    return value


def _schema(raw: Any, name: str, schema: int) -> dict[str, Any]:
    if not isinstance(raw, dict) or raw.get("schema") != schema:
        found = raw.get("schema") if isinstance(raw, dict) else None
        raise ValueError(f"{name}: unsupported schema {found!r} (this atlas reads schema {schema})")
    return raw


# Field sets as frozensets: a module-level string tuple reads as a published
# value list to the contract reference, and these are file fields, not values.
_TABLE_FIELDS = frozenset({"schema", "spec", "table_version", "sources", "rows", "kinds", "keys", "mappings"})
_MAPPING_FIELDS = frozenset({"source", "key", "row", "relation", "via", "citation", "valid_from", "valid_to"})


def _sources(raw: Any) -> dict[str, tuple[_Pin, ...]]:
    """Each column with the projects it is read from: per project its name and pinned version (#784 D42)."""
    if not isinstance(raw, dict) or not raw:
        raise ValueError("platform_table: 'sources' must be a non-empty object")
    versions: dict[str, tuple[_Pin, ...]] = {}
    for source, entries in raw.items():
        where = f"platform_table source {source!r}"
        if not isinstance(entries, list) or not entries:
            raise ValueError(f"{where}: must be a non-empty list of the projects it is read from")
        pins: list[_Pin] = []
        for entry in entries:
            entry = _expect_dict(entry, where, ("upstream", "version", "revision"))
            _expect_str(entry["revision"], f"{where}: revision")
            upstream = _expect_str(entry["upstream"], f"{where}: upstream")
            pins.append((upstream, _expect_str(entry["version"], f"{where}: version")))
        if len({upstream for upstream, _ in pins}) != len(pins):
            raise ValueError(f"{where}: a project is listed twice")
        versions[_expect_str(source, "source name")] = tuple(pins)
    if FOLDER_SOURCE in versions:
        raise ValueError(f"platform_table: {FOLDER_SOURCE!r} is the bare-folder pseudo-source, not a source")
    return versions


def runs_from(pins: tuple[_Pin, ...]) -> str:
    """The version a column's mappings run from: its one project's, or each project's named, comma-separated."""
    if len(pins) == 1:
        return pins[0][1]
    return ", ".join(f"{upstream} {version}" for upstream, version in pins)


def _rows(raw: Any) -> frozenset[str]:
    if not isinstance(raw, list) or not raw:
        raise ValueError("platform_table: 'rows' must be a non-empty list of row names")
    rows = frozenset(_expect_str(row, "row name") for row in raw)
    if len(rows) != len(raw):
        raise ValueError("platform_table: a row is listed twice")
    return rows


def _expect_kind(kind: Any, where: str) -> str:
    if kind not in PLATFORM_KINDS:
        raise ValueError(f"{where}: kind {kind!r} is not one of {', '.join(PLATFORM_KINDS)}")
    return kind


def _key_kinds(raw: Any, keys: Mapping[str, frozenset[str]]) -> dict[tuple[str, str], str]:
    """The kinds the catalogues state about their own keys, each cited (#784 D16)."""
    if not isinstance(raw, dict):
        raise ValueError("platform_table: 'kinds' must be an object")
    stated: dict[tuple[str, str], str] = {}
    for source, entries in raw.items():
        if source not in keys or not isinstance(entries, dict):
            raise ValueError(f"platform_table kinds {source!r}: not a source, or not an object")
        for key, entry in entries.items():
            where = f"platform_table kinds {source}/{key}"
            if key not in keys[source]:
                raise ValueError(f"{where}: the key is not listed under 'keys'")
            entry = _expect_dict(entry, where, ("kind", "citation"))
            _expect_str(entry["citation"], f"{where}: citation")
            stated[(source, key)] = _expect_kind(entry["kind"], where)
    return stated


def _keys(raw: Any, sources: Mapping[str, object]) -> dict[tuple[str, str], str]:
    """Every key of every source with the citation of where the source states it."""
    if not isinstance(raw, dict) or set(raw) != set(sources):
        raise ValueError("platform_table: 'keys' lists exactly the sources")
    cited: dict[tuple[str, str], str] = {}
    for source, entries in raw.items():
        if not isinstance(entries, dict) or not entries:
            raise ValueError(f"platform_table keys {source!r}: must be a non-empty object")
        for key, citation in entries.items():
            _expect_str(key, f"platform_table keys {source!r}")
            cited[(source, key)] = _expect_str(citation, f"platform_table keys {source!r} {key!r}: citation")
    return cited


def _required_columns(sources: Mapping[str, object]) -> None:
    """The columns the questions read by name are there — a table without them would answer nothing, silently."""
    missing = [c for c in dict.fromkeys((ESDE_SOURCE, ESDE_PLATFORM_SOURCE, *FOLDER_SOURCES)) if c not in sources]
    if missing:
        raise ValueError(f"platform_table: the questions read the column(s) {', '.join(missing)}, which it lacks")


def _relations_hold(stated: Mapping[tuple[str, str], Mapping[str, str]]) -> None:
    """A generated relation is the one its key's row count implies, or the file says something the loader will not."""
    for (source, key), rows in stated.items():
        expected = EXACT_MATCH if len(rows) == 1 else BROAD_MATCH
        relations = set(rows.values())
        if relations != {expected}:
            raise ValueError(
                f"platform_table mapping {source}/{key}: on {len(rows)} row(s) the relation is {expected}, "
                f"the file states {', '.join(sorted(relations))}"
            )


def _mapping(
    entry: Any, sources: Mapping[str, tuple[_Pin, ...]], keys: Mapping[str, frozenset[str]], rows: frozenset[str]
) -> tuple[str, str, str, str, str]:
    entry = _expect_dict(entry, "platform_table mapping", _MAPPING_FIELDS)
    source = _expect_str(entry["source"], "mapping source")
    key = _expect_str(entry["key"], "mapping key")
    where = f"platform_table mapping {source}/{key}"
    if source not in sources or key not in keys[source]:
        raise ValueError(f"{where}: the key is not listed under 'keys'")
    if entry["row"] not in rows:
        raise ValueError(f"{where}: row {entry['row']!r} is not a row")
    if entry["relation"] not in PLATFORM_RELATIONS:
        raise ValueError(f"{where}: relation {entry['relation']!r} is not one of {PLATFORM_RELATIONS}")
    _expect_str(entry["via"], f"{where}: via")
    citation = _expect_str(entry["citation"], f"{where}: citation")
    if entry["valid_from"] != runs_from(sources[source]) or entry["valid_to"] is not None:
        raise ValueError(f"{where}: an entry runs from its source's pinned version, open-ended")
    return source, key, entry["row"], entry["relation"], citation


_OVERRIDE_FIELDS = {
    "merge": {"merge", "into", "reason", "citation"},
    "map": {"source", "key", "rows", "relation", "reason", "citation"},
    "kind": {"row_of", "kind", "subset_of", "reason", "citation"},
}


def _override_shape(entry: Any) -> str:
    for shape, fields in _OVERRIDE_FIELDS.items():
        if isinstance(entry, dict) and set(entry) == fields:
            return shape
    raise ValueError(f"platform_overrides: an override is a merge, a map or a kind, got {entry!r}")


def _fragments(citations: Iterable[str]) -> set[str]:
    return {fragment for citation in citations for fragment in citation.split(_SEPARATOR)}


def _added(evidence: str | None, attached: Iterable[str], where: str) -> list[str]:
    """*evidence*, as the citations it adds to what the loader attaches anyway; a repeated fragment is refused."""
    if evidence is None:
        return []
    repeated = sorted(_fragments((evidence,)) & _fragments(attached))
    if repeated:
        raise ValueError(f"{where}: citation repeats {'; '.join(repeated)}, which the loader attaches from the anchors")
    return [evidence]


def _stated(entry: dict[str, Any], where: str) -> str | None:
    """The evidence an override adds beyond its anchors' own citations, ``None`` for none; its reason is checked."""
    _expect_str(entry["reason"], f"{where}: reason")
    if entry["citation"] is None:
        return None
    return _expect_str(entry["citation"], f"{where}: citation")


class _Overrides:
    """The three kinds of hand judgement, applied over the generated placements in a fixed order.

    *merge* says two generated rows are one system (a renamed key, a duplicate
    slug): every key placed on the merged row moves to the other. *map*
    replaces one key's row set — a key broader, narrower or only related to
    what the generator placed it on. *kind* states a row's kind where no
    catalogue does or where catalogues disagree, and the row it is a content
    subset of, if any. Merges run first, maps resolve their anchors through the
    merges, kinds come last; every anchor is a ``(source, key)`` the source
    has at its pin (#784 D2), never a row name, and never a key that is
    excluded. A key a map replaces is no anchor for another judgement: the
    anchor would name the rows the generator gave it, not the ones the map
    does. A merge or a map is cited by its anchors' own citations, which the
    loader attaches, plus whatever further evidence the entry states; a kind
    reaches no answer, so nothing is attached to it.
    """

    def __init__(
        self,
        keys: Mapping[tuple[str, str], str],
        generated: Mapping[tuple[str, str], Mapping[str, _Placement]],
        kinds: dict[str, str],
        excluded: Mapping[tuple[str, str], str],
    ) -> None:
        self.keys = keys
        self.generated = generated
        self.kinds = kinds
        self.excluded = excluded
        self.into: dict[str, str] = {}
        self.merge_citations: dict[str, tuple[str, ...]] = {}
        self.subset_of: dict[str, str] = {}
        self.mapped: dict[tuple[str, str], dict[str, _Placement]] = {}
        self.referenced: dict[tuple[str, str], str] = {}

    def anchor(self, raw: Any, where: str, *, reference: bool = True) -> tuple[str, str]:
        """A ``(source, key)`` the source has at its pin and no exclusion names; *reference* marks a row anchor."""
        entry = _expect_dict(raw, where, ("source", "key"))
        pair = (entry["source"], entry["key"])
        if pair not in self.keys:
            raise ValueError(f"{where}: {pair[0]}/{pair[1]} is not a key of its source at the pin")
        if pair in self.excluded:
            raise ValueError(f"{where}: {pair[0]}/{pair[1]} is excluded, so no judgement may also name it")
        if reference:
            self.referenced.setdefault(pair, where)
        return pair

    def check_references(self) -> None:
        for pair, where in self.referenced.items():
            if pair in self.mapped:
                raise ValueError(
                    f"{where}: {pair[0]}/{pair[1]} is itself mapped, so as an anchor it would name the "
                    "generated rows, not the mapped ones"
                )

    def row(self, row: str) -> str:
        while row in self.into:
            row = self.into[row]
        return row

    def _chain(self, row: str) -> tuple[str, ...]:
        """The citations of every merge a generated row went through — the evidence for where its keys now sit."""
        cited: list[str] = []
        while row in self.into:
            cited.extend(self.merge_citations[row])
            row = self.into[row]
        return tuple(cited)

    def rows_of(self, anchor: tuple[str, str], where: str) -> tuple[str, ...]:
        rows = tuple(dict.fromkeys(self.row(r) for r in self.generated.get(anchor, {})))
        if not rows:
            raise ValueError(f"{where}: {anchor[0]}/{anchor[1]} is placed on no row")
        return rows

    def one_row(self, raw: Any, where: str) -> tuple[tuple[str, str], str]:
        anchor = self.anchor(raw, where)
        rows = self.rows_of(anchor, where)
        if len(rows) != 1:
            raise ValueError(f"{where}: the anchor covers {len(rows)} rows, this names one")
        return anchor, rows[0]

    def merge(self, entry: dict[str, Any]) -> None:
        where = f"platform_overrides merge {entry['merge']!r}"
        evidence = _stated(entry, where)
        (merged_key, merged), (into_key, into) = self.one_row(entry["merge"], where), self.one_row(entry["into"], where)
        if merged == into:
            raise ValueError(f"{where}: the two anchors are on one row already")
        self.into[merged] = into
        attached = (self.keys[merged_key], self.keys[into_key])
        self.merge_citations[merged] = (*attached, *_added(evidence, attached, where))

    def map(self, entry: dict[str, Any]) -> None:
        where = f"platform_overrides map {entry.get('source')}/{entry.get('key')}"
        target = self.anchor({"source": entry["source"], "key": entry["key"]}, where, reference=False)
        if target in self.mapped:
            raise ValueError(f"{where}: a key is mapped once")
        relation = entry["relation"]
        if relation is not None and relation not in (NARROW_MATCH, RELATED_MATCH):
            raise ValueError(f"{where}: an override sets only narrowMatch or relatedMatch, got {relation!r}")
        if not isinstance(entry["rows"], list) or not entry["rows"]:
            raise ValueError(f"{where}: rows must name at least one (source, key) anchor")
        evidence = _stated(entry, where)
        anchors = [self.anchor(raw, f"{where}: rows[{index}]") for index, raw in enumerate(entry["rows"])]
        attached = (self.keys[target], *(self.keys[a] for a in anchors))
        citations = _fragments_once((*attached, *_added(evidence, attached, where)))
        rows: dict[str, _Placement] = {}
        for index, anchor in enumerate(anchors):
            for row in self.rows_of(anchor, f"{where}: rows[{index}]"):
                rows[row] = _Placement(_MAPPED_COVERAGE[relation], citations)
        self.mapped[target] = rows

    def kind(self, entry: dict[str, Any]) -> None:
        where = f"platform_overrides kind of {entry.get('row_of')!r}"
        _stated(entry, where)
        _, row = self.one_row(entry["row_of"], where)
        if row in self.kinds:
            raise ValueError(f"{where}: a row's kind is stated once")
        self.kinds[row] = _expect_kind(entry["kind"], where)
        if entry["subset_of"] is None and self.kinds[row] == _CONTENT_SUBSET_KIND:
            raise ValueError(f"{where}: a {_CONTENT_SUBSET_KIND} row names the row it is a subset_of")
        if entry["subset_of"] is not None:
            if self.kinds[row] != _CONTENT_SUBSET_KIND:
                raise ValueError(
                    f"{where}: a row with a subset_of is a content subset, so its kind is "
                    f"{_CONTENT_SUBSET_KIND}, not {self.kinds[row]}"
                )
            _, parent = self.one_row(entry["subset_of"], f"{where}: subset_of")
            if parent == row:
                raise ValueError(f"{where}: subset_of names the row itself, and a row is no subset of itself")
            self.subset_of[row] = parent

    def check_subsets(self) -> None:
        """A subset's parent is a system of its own, never another subset — a part is a part of one row."""
        for row, parent in self.subset_of.items():
            if parent in self.subset_of:
                raise ValueError(
                    f"platform_overrides: the row a subset_of names is itself a subset of another, so the part "
                    f"would be a part of a part ({row} in {parent} in {self.subset_of[parent]})"
                )

    def placements(self) -> dict[tuple[str, str], dict[str, _Placement]]:
        """Every key's rows after the judgements — a map stands whether or not the generator placed its key."""
        final: dict[tuple[str, str], dict[str, _Placement]] = dict(self.mapped)
        for anchor, rows in self.generated.items():
            if anchor in self.mapped:
                continue
            # Two generated rows a merge folds into one keep every citation either placement stood on,
            # each line once (#784 D38).
            moved: dict[str, _Placement] = {}
            for row, placement in rows.items():
                target = self.row(row)
                earlier = moved[target].citations if target in moved else ()
                cited = _fragments_once((*earlier, *placement.citations, *self._chain(row)))
                moved[target] = _Placement(placement.coverage, cited)
            final[anchor] = moved
        return final


def _apply_overrides(
    raw: Any,
    keys: Mapping[tuple[str, str], str],
    generated: Mapping[tuple[str, str], Mapping[str, _Placement]],
    kinds: dict[str, str],
    excluded: Mapping[tuple[str, str], str],
) -> tuple[dict[tuple[str, str], dict[str, _Placement]], dict[str, str]]:
    raw = _expect_dict(
        _schema(raw, "platform_overrides", PLATFORM_OVERRIDES_SCHEMA),
        "platform_overrides",
        ("schema", "spec", "overrides"),
    )
    entries = raw["overrides"]
    if not isinstance(entries, list):
        raise ValueError("platform_overrides: 'overrides' must be a list")
    shaped = [(_override_shape(entry), entry) for entry in entries]
    overrides = _Overrides(keys, generated, kinds, excluded)
    for wanted in ("merge", "map", "kind"):
        for shape, entry in shaped:
            if shape == wanted:
                getattr(overrides, shape)(entry)
    overrides.check_references()
    overrides.check_subsets()
    return overrides.placements(), overrides.subset_of


def _row_kind(
    row: str,
    overridden: Mapping[str, str],
    stated: Mapping[tuple[str, str], str],
    placements: Mapping[tuple[str, str], Mapping[str, _Placement]],
) -> str:
    """A row's kind: a hand judgement first, else what a catalogue states about a key on it.

    A key alone on the row speaks before a key that covers more rows, and the
    catalogues speak in their table order. A row nobody classifies is
    ``unclassified``, which the release check refuses.
    """
    if row in overridden:
        return overridden[row]
    candidates = sorted(
        (len(placements[pair]) > 1, index, kind)
        for index, (pair, kind) in enumerate(stated.items())
        if row in placements.get(pair, {})
    )
    return candidates[0][2] if candidates else UNCLASSIFIED_KIND


def _subsets_named(row_kinds: Mapping[str, str], subset_of: Mapping[str, str]) -> None:
    """Every row of kind content-subset names its parent — a catalogue's kind cannot make one (#784 D37)."""
    unnamed = sorted(row for row, kind in row_kinds.items() if kind == _CONTENT_SUBSET_KIND and row not in subset_of)
    if unnamed:
        raise ValueError(
            f"platform_table: row(s) {', '.join(unnamed)} are of kind {_CONTENT_SUBSET_KIND} but name no row "
            "they are a subset_of"
        )


def _kind_conflicts(
    rows: Iterable[str],
    overridden: Mapping[str, str],
    stated: Mapping[tuple[str, str], str],
    placements: Mapping[tuple[str, str], Mapping[str, _Placement]],
) -> dict[str, tuple[str, ...]]:
    """Rows whose catalogues state different kinds and no hand judgement settles — a conflict kept as data (D17)."""
    conflicts: dict[str, tuple[str, ...]] = {}
    for row in rows:
        kinds = {kind for pair, kind in stated.items() if row in placements.get(pair, {})}
        if len(kinds) > 1 and row not in overridden:
            conflicts[row] = tuple(sorted(kinds))
    return conflicts


def _excluded(raw: Any, keys: Mapping[tuple[str, str], str]) -> dict[tuple[str, str], str]:
    """The keys deliberately placed on no row, each with its reason (#784 D17)."""
    raw = _expect_dict(
        _schema(raw, "platform_excluded", PLATFORM_EXCLUDED_SCHEMA),
        "platform_excluded",
        ("schema", "spec", "excluded"),
    )
    if not isinstance(raw["excluded"], list):
        raise ValueError("platform_excluded: 'excluded' must be a list")
    excluded: dict[tuple[str, str], str] = {}
    for entry in raw["excluded"]:
        entry = _expect_dict(entry, "platform_excluded entry", ("source", "key", "reason"))
        where = f"platform_excluded {entry['source']}/{entry['key']}"
        pair = (entry["source"], entry["key"])
        if pair not in keys:
            raise ValueError(f"{where}: {pair[0]}/{pair[1]} is not a key of its source at the pin")
        if pair in excluded:
            raise ValueError(f"{where}: a key is excluded once")
        excluded[pair] = _expect_str(entry["reason"], f"{where}: reason")
    return excluded


def load_platform_table(
    table_text: str | None = None,
    overrides_text: str | None = None,
    excluded_text: str | None = None,
) -> PlatformTable:
    """Load the packaged table, apply the overrides and the exclusions (or the texts supplied) — fail-closed.

    Every refusal is an answer a question could otherwise be given out of a
    table that does not add up: an unreadable schema, a missing column the
    questions read by name (``esde``, ``esde-platform``, a folder
    vocabulary), a key placed but not listed, a row that does not exist, a
    relation outside the SKOS four or other than its key's row count implies,
    an uncited mapping, an entry not open-ended at its source's pin, and an
    override that names a key its source does not have at the pin or an
    excluded key, an anchor placed on nothing or itself mapped, a merge of a
    row into itself, a row stated as a subset of itself or of a row that is
    a subset itself, one key mapped twice, or a merge's or a map's evidence
    repeating a citation, or a part of one, the loader attaches from the
    anchors anyway. Overrides anchor on ``(source, key)`` pairs, never on row names,
    and apply in a fixed order whatever order the file lists them in (see
    :class:`_Overrides`). An excluded key (``platform_excluded.json``) is
    placed on no row; its reason is kept. A row no key covers after that
    leaves the table.
    """
    if table_text is None:
        table_text = packaged_text("platform_table.json")
    if overrides_text is None:
        overrides_text = packaged_text("platform_overrides.json")
    if excluded_text is None:
        excluded_text = packaged_text("platform_excluded.json")
    raw = _schema(json.loads(table_text), "platform_table", PLATFORM_TABLE_SCHEMA)
    raw = _expect_dict(raw, "platform_table", _TABLE_FIELDS)
    version = raw["table_version"]
    if not isinstance(version, int) or isinstance(version, bool) or version < 1:
        raise ValueError(f"platform_table: table_version must be a positive integer, got {version!r}")
    sources = _sources(raw["sources"])
    _required_columns(sources)
    rows = _rows(raw["rows"])
    cited = _keys(raw["keys"], sources)
    keys = {source: frozenset(k for s, k in cited.keys() if s == source) for source in sources}
    stated_kinds = _key_kinds(raw["kinds"], keys)
    if not isinstance(raw["mappings"], list):
        raise ValueError("platform_table: 'mappings' must be a list")
    generated: dict[tuple[str, str], dict[str, _Placement]] = {}
    stated: dict[tuple[str, str], dict[str, str]] = {}
    for entry in raw["mappings"]:
        source, key, row, relation, citation = _mapping(entry, sources, keys, rows)
        if row in generated.setdefault((source, key), {}):
            raise ValueError(f"platform_table mapping {source}/{key}: row {row!r} placed twice")
        generated[(source, key)][row] = _Placement(_WHOLE, (citation,))
        stated.setdefault((source, key), {})[row] = relation
    _relations_hold(stated)
    excluded = _excluded(json.loads(excluded_text), cited)
    kinds: dict[str, str] = {}
    placements, subset_of = _apply_overrides(json.loads(overrides_text), cited, generated, kinds, excluded)
    final = {anchor: rows for anchor, rows in placements.items() if rows and anchor not in excluded}
    by_row: dict[str, dict[str, list[str]]] = {}
    for (source, key), rows in final.items():
        for row in rows:
            by_row.setdefault(row, {}).setdefault(source, []).append(key)
    row_kinds = {row: _row_kind(row, kinds, stated_kinds, final) for row in by_row}
    _subsets_named(row_kinds, subset_of)
    return PlatformTable(
        table_version=version,
        sources=MappingProxyType(sources),
        keys=MappingProxyType(keys),
        kinds=MappingProxyType(row_kinds),
        kind_conflicts=MappingProxyType(_kind_conflicts(by_row, kinds, stated_kinds, final)),
        subset_of=MappingProxyType({row: parent for row, parent in subset_of.items() if row in by_row}),
        excluded=MappingProxyType(excluded),
        placements=MappingProxyType({a: MappingProxyType(r) for a, r in final.items()}),
        by_row=MappingProxyType(
            {row: MappingProxyType({s: tuple(sorted(k)) for s, k in per.items()}) for row, per in by_row.items()}
        ),
    )


_PACKAGED: PlatformTable | None = None


def platform_table() -> PlatformTable:
    """The packaged table, loaded once."""
    global _PACKAGED
    if _PACKAGED is None:
        _PACKAGED = load_platform_table()
    return _PACKAGED


def known_platform_vocabularies() -> tuple[str, ...]:
    """Every source a pair may name, in table order — the table's own columns."""
    return tuple(platform_table().sources)


# --- the pure lookup --------------------------------------------------------


def _pair(raw: Any) -> tuple[str, str, str | None]:
    if not isinstance(raw, (tuple, list)) or len(raw) not in (2, 3):
        raise ValueError(f"a platform pair is (source, key) or (source, key, version), got {raw!r}")
    source, key, *rest = raw
    version = rest[0] if rest else None
    for name, value in (("source", source), ("key", key)):
        if not isinstance(value, str):
            raise ValueError(
                f"platform pair {name}: expected a string, got {value!r} "
                f"(a numeric id is asked for as its decimal string)"
            )
    if version is not None and not isinstance(version, str):
        raise ValueError(f"platform pair version: expected a string or None, got {version!r}")
    return source, key.strip(), version


# What one pair, or several pairs together, means: each row it reaches with how
# much of that row it covers, and whose cover that is — the key whose own
# placement it is, so that a key compared with a part it alone defines is that
# part, not merely a part. A bare folder's cover is the placement of the folder
# vocabulary that spells the key on that row. ``None`` where no single key
# defines the cover: two pairs that each cover the row whole, or different
# parts or overlaps met.
_Pair = tuple[str, str]
_Cover = tuple[_Coverage, _Pair | None]
_Asked = Mapping[str, _Cover]


def _extent(placements: Mapping[str, _Placement]) -> dict[str, _Coverage]:
    return {row: placement.coverage for row, placement in placements.items()}


def _rows_of_pair(table: PlatformTable, source: str, key: str) -> dict[str, _Cover]:
    if source == FOLDER_SOURCE:
        union: dict[str, _Cover] = {}
        for folder in FOLDER_SOURCES:
            for row, placement in table.placements.get((folder, key), {}).items():
                union.setdefault(row, (placement.coverage, (folder, key)))
        return _inside_whole_parents(table, union)
    rows: dict[str, _Cover] = {
        row: (p.coverage, (source, key)) for row, p in table.placements.get((source, key), {}).items()
    }
    return _inside_whole_parents(table, rows)


def _inside_whole_parents(table: PlatformTable, rows: Mapping[str, _Cover]) -> dict[str, _Cover]:
    """*rows* without a content subset whose parent they cover whole: the parent already holds it (#784 D37).

    A key placed on a row and on that row's own subsets (RomM's doom on doom
    and on the engine folders' rows) means the row; kept, the subset would meet
    another subset of the parent as a different part although the parent is
    covered whole.
    """
    return {
        row: cover
        for row, cover in rows.items()
        if (parent := table.subset_of.get(row)) is None or rows.get(parent, (None, None))[0] != _WHOLE
    }


def _covers(table: PlatformTable, levels: Mapping[str, _Coverage], row: str) -> bool:
    """*levels* cover *row* whole: itself, or the row it is a content subset of (#784 D37)."""
    parent = table.subset_of.get(row)
    return levels.get(row) == _WHOLE or (parent is not None and levels.get(parent) == _WHOLE)


def _relation(table: PlatformTable, asked: _Asked, key: _Pair, other: Mapping[str, _Coverage]) -> PlatformRelation:
    """The relation of *key*, reaching *other*, to what *asked* reaches, row by row.

    The two are compared as sets of rows with how much of each row they cover,
    a content subset counting as a part of its parent row. Where *asked* covers
    a row with *key*'s own cover, *key* covers that row exactly as asked. The
    same rows wholly, or the very part, is ``exactMatch``; the other holding all
    of the asked and more is ``broadMatch``; the asked holding all of the other
    and more is ``narrowMatch``; anything else — two keys that each cover part
    of a shared row, two content subsets of one row, an overlap — is
    ``relatedMatch``. The asked key is exact to itself this way, and the
    relation of A to B is always the inverse of B to A.
    """
    levels: dict[str, _Coverage] = {row: level for row, (level, _) in asked.items()}
    up = all(
        origin == key or (level != _OVERLAP and _covers(table, other, row)) for row, (level, origin) in asked.items()
    )
    down = all(
        asked.get(row, (None, None))[1] == key or (level != _OVERLAP and _covers(table, levels, row))
        for row, level in other.items()
    )
    if up and down:
        return EXACT_MATCH
    if up:
        return BROAD_MATCH
    if down:
        return NARROW_MATCH
    return RELATED_MATCH


def _reached(table: PlatformTable, rows: Iterable[str]) -> set[str]:
    """*rows*, the rows they are content subsets of, and every content subset of either — whose keys an answer lists.

    A content subset of a reached row's parent is a sibling of that row: its keys are listed as two map parts of
    one row list each other (#784 D37).
    """
    reached = set(rows) | {table.subset_of[row] for row in rows if row in table.subset_of}
    return reached | {child for child, parent in table.subset_of.items() if parent in reached}


def _source_keys(table: PlatformTable, asked: _Asked) -> tuple[PlatformSourceKeys, ...]:
    rows = _reached(table, asked)
    answers: list[PlatformSourceKeys] = []
    for source in table.sources:
        keys = sorted({key for row in rows for key in table.by_row.get(row, {}).get(source, ())})
        found = tuple(
            PlatformKey(
                key,
                _relation(table, asked, (source, key), _extent(table.placements[(source, key)])),
                _fragments_once(sorted({c for p in table.placements[(source, key)].values() for c in p.citations})),
            )
            for key in keys
        )
        answers.append(PlatformSourceKeys(source, KEYS_FOUND if found else KEYS_NONE, found))
    return tuple(answers)


def _version_caveat(table: PlatformTable, source: str, key: str, version: str) -> Caveat | None:
    if source == FOLDER_SOURCE:
        return Caveat(
            CAVEAT_PLATFORM_VERSION_UNAPPLIED,
            "a bare folder name is matched against every folder vocabulary, so a version names no "
            "single source and was not applied — ask the folder vocabulary by name to have it applied",
            {"source": source, "key": key, "version": version},
        )
    pins = table.sources.get(source)
    if pins is None or any(pinned == version for _, pinned in pins):
        return None
    return Caveat(
        CAVEAT_PLATFORM_SOURCE_VERSION_DIFFERS,
        "the table holds this source at another version — the key is answered as it stands "
        "at the pinned version, which may not be what it meant at the stated one",
        {"source": source, "key": key, "version": version, "pins": dict(pins)},
    )


def _exclusion(table: PlatformTable, source: str, key: str) -> str | None:
    """The recorded reason the table places *key* nowhere — for a bare folder, the first folder vocabulary's."""
    if source != FOLDER_SOURCE:
        return table.excluded.get((source, key))
    return next((table.excluded[(f, key)] for f in FOLDER_SOURCES if (f, key) in table.excluded), None)


def _unknown_pair(table: PlatformTable, source: str, key: str) -> Caveat:
    """Why a pair answers ``unknown``: no such source (#784 D31), a key excluded on purpose (D35), or no such key."""
    if source != FOLDER_SOURCE and source not in table.sources:
        return Caveat(
            CAVEAT_PLATFORM_SOURCE_UNKNOWN,
            "the table includes no such source — a misspelt source name, or a vocabulary the "
            "table does not carry; no key of it can be translated",
            {"source": source, "key": key, "sources": tuple(table.sources)},
        )
    reason = _exclusion(table, source, key)
    if reason is not None:
        return Caveat(
            CAVEAT_PLATFORM_EXCLUDED,
            "the source has this key and the table places it on no row on purpose, for the "
            "recorded reason — no system is named for it",
            {"source": source, "key": key, "reason": reason},
        )
    return Caveat(
        CAVEAT_PLATFORM_UNMAPPED,
        "the table holds no such key in this source — no system corresponds, and "
        "naming a folder after the raw key would name one no catalogue declares",
        {"source": source, "key": key},
    )


def translate(pairs: Sequence[Sequence[str | None]], table: PlatformTable | None = None) -> PlatformTranslation:
    """What each asked ``(source, key)`` pair means in every source, and what they share.

    A pair is ``(source, key)`` or ``(source, key, version)``. *source* is one of
    :func:`known_platform_vocabularies`, or ``"folder"`` for a bare folder name,
    which means the union of what every folder vocabulary means by it (#784
    D14). *key* is the source's own key, a numeric id as its decimal string,
    compared exactly as the source spells it, case included (D34), after
    surrounding whitespace is stripped. A pair the table holds no key for
    answers ``unknown`` with the ``platform-unmapped`` caveat, a key the table
    excludes on purpose with ``platform-excluded`` and its recorded reason
    (D35), and a pair in a source the table does not include with
    ``platform-source-unknown`` (D31); each is a definite answer, never a
    guess, and none raises.

    Per pair, every source states its keys for the systems the pair names, each
    with its relation to the pair and its citations, or ``none``; a row that is
    a content subset of another answers as a part of it (D37). Across pairs,
    the systems every known pair names are their intersection, each with how
    much of it the pairs cover together, and every source's keys relate to that
    composite by the same rule (D36); pairs that share a system only through
    different parts or overlaps of it carry ``platform-parts-unestablished``
    (D40), and when they share none, ``conflict`` names the known pairs and
    atlas picks none (D9). A pair whose stated version is none of the pinned
    versions of that source's column carries the
    ``platform-source-version-differs`` caveat (D11, D42), and a version on a
    bare folder pair the ``platform-version-unapplied`` caveat (D32). At least
    one pair is asked; a malformed pair raises.
    """
    if table is None:
        table = platform_table()
    parsed = [_pair(raw) for raw in pairs]
    if not parsed:
        raise ValueError("translate needs at least one (source, key) pair")
    answers: list[PlatformPairAnswer] = []
    caveats: list[Caveat] = []
    known: list[dict[str, _Cover]] = []
    for source, key, version in parsed:
        rows = _rows_of_pair(table, source, key)
        if version is not None and (stated := _version_caveat(table, source, key, version)):
            caveats.append(stated)
        if not rows:
            answers.append(PlatformPairAnswer(source, key, version, PAIR_UNKNOWN, ()))
            caveats.append(_unknown_pair(table, source, key))
            continue
        answers.append(PlatformPairAnswer(source, key, version, PAIR_KNOWN, _source_keys(table, rows)))
        known.append(rows)
    return _with_intersection(table, tuple(answers), known, tuple(caveats))


def _together(one: _Cover, other: _Cover) -> _Cover:
    """How much of a row two pairs cover together, and whose cover that is (#784 D36).

    Whole only where both are whole. A part (or an overlap) met with the whole
    row stays that key's part; two covers of one key stay that key's; two
    different parts are a part no single key defines, or an overlap if both
    are overlaps.
    """
    (level, origin), (other_level, other_origin) = one, other
    if level == _WHOLE and other_level == _WHOLE:
        return (_WHOLE, None)
    if level == _WHOLE or other_level == _WHOLE:
        part_level, part_origin = other if level == _WHOLE else one
        return (_PART if part_level == _OVERLAP else part_level, part_origin)
    if origin is not None and origin == other_origin:
        return (level if level == other_level else _PART, origin)
    return (_OVERLAP if level == other_level == _OVERLAP else _PART, None)


# Where pairs meet only through different parts of a row: the system is
# shared, and no key defines what of it they share (#784 D40).
_PARTS_MEET: _Cover = (_PART, None)


def _meeting(table: PlatformTable, row: str, cover: _Cover, other: _Asked) -> tuple[str, _Cover] | None:
    """Where a row of one extent meets *other*, a row *other* lacks, and how much of it they cover together.

    A content subset meets its parent row: inside it where the parent is
    covered whole, and on the parent, through different parts, where the parent
    is covered only in part or another content subset of it is (#784 D37, D40).
    """
    parent = table.subset_of.get(row)
    if parent is None:
        return None
    if parent in other:
        if other[parent][0] == _WHOLE:
            return row, _together(cover, (_WHOLE, None))
        return parent, _PARTS_MEET
    if any(table.subset_of.get(sibling) == parent for sibling in other):
        return parent, _PARTS_MEET
    return None


def _shared(table: PlatformTable, one: _Asked, other: _Asked) -> dict[str, _Cover]:
    """The rows two extents share, with how much of each they cover together; a subset meets its parent (D37, D40)."""
    shared = {row: _together(cover, other[row]) for row, cover in one.items() if row in other}
    for mine, theirs in ((one, other), (other, one)):
        for row, cover in mine.items():
            if row not in theirs and (met := _meeting(table, row, cover, theirs)) is not None:
                shared.setdefault(*met)
    return shared


def _meet_through_parts(composite: _Asked) -> tuple[str, ...]:
    """The composite's rows the pairs share only through different parts or overlaps of them (#784 D40)."""
    return tuple(sorted(row for row, (level, origin) in composite.items() if level != _WHOLE and origin is None))


def _parts_unestablished(
    table: PlatformTable, answers: Sequence[PlatformPairAnswer], known: Sequence[_Asked], rows: Sequence[str]
) -> Caveat:
    """The statement that the pairs share *rows* through parts or overlaps the table cannot compare, naming them."""
    known_answers = [a for a in answers if a.status == PAIR_KNOWN]
    meeting = [
        answer
        for answer, extent in zip(known_answers, known, strict=True)
        if not all(_covers(table, {r: level for r, (level, _) in extent.items()}, row) for row in rows)
    ]
    return Caveat(
        CAVEAT_PLATFORM_PARTS_UNESTABLISHED,
        "the pairs share this system only through different parts or overlaps of it, and "
        "the table cannot know whether those share content — the shared system is named, "
        "which of its content the pairs share is not",
        {"sources": tuple(a.source for a in meeting), "keys": tuple(a.key for a in meeting)},
    )


def _with_intersection(
    table: PlatformTable,
    answers: tuple[PlatformPairAnswer, ...],
    known: list[dict[str, _Cover]],
    caveats: tuple[Caveat, ...],
) -> PlatformTranslation:
    versions = tuple(PlatformSourceVersion(s, u, v) for s, pins in table.sources.items() for u, v in pins)
    known_answers = tuple(a for a in answers if a.status == PAIR_KNOWN)
    if not known:
        return PlatformTranslation(table.table_version, versions, answers, INTERSECTION_UNKNOWN, (), (), caveats)
    if len(known) == 1:
        intersection = known_answers[0].sources
    else:
        composite = known[0]
        for rows in known[1:]:
            composite = _shared(table, composite, rows)
        if not composite:
            return PlatformTranslation(
                table.table_version, versions, answers, INTERSECTION_CONFLICT, (), known_answers, caveats
            )
        intersection = _source_keys(table, composite)
        if parts := _meet_through_parts(composite):
            caveats = (*caveats, _parts_unestablished(table, answers, known, parts))
    return PlatformTranslation(
        table.table_version, versions, answers, INTERSECTION_AGREED, intersection, (), caveats
    )


def _intersection_keys(
    translation: PlatformTranslation, columns: Sequence[str], relations: Sequence[str] = PLATFORM_RELATIONS
) -> tuple[str, ...]:
    """The keys the translation's intersection holds in *columns* under *relations*, sorted."""
    return tuple(
        sorted(
            {
                k.key
                for keys in translation.intersection
                if keys.source in columns
                for k in keys.keys
                if k.relation in relations
            }
        )
    )


def systems_named(translation: PlatformTranslation, columns: Sequence[str] = (ESDE_SOURCE,)) -> tuple[str, ...]:
    """The system names the translation's intersection holds in *columns*, sorted — the machine half's join key.

    *columns* are the catalogue columns an installation deploys: ES-DE's names
    for every arrangement, RetroDECK's own for a RetroDECK, whose catalogue
    adds systems ES-DE has not (``primehack``, ``portmaster``).
    """
    return _intersection_keys(translation, columns)


def names_one_system(source: str, key: str, table: PlatformTable | None = None) -> bool:
    """Whether *key* of *source* names exactly one system: it is placed on one row and covers it whole.

    A tag that covers more (``arcade``) names none of its systems alone, and
    neither does a key an override says covers only part of its row. This is
    the reverse question — which one system a hand-added system's tag stands
    for — and not :func:`exact_platform_tags`', which asks whether a tag
    covers exactly what a pair was asked for.
    """
    if table is None:
        table = platform_table()
    rows = table.placements.get((source, key), {})
    return len(rows) == 1 and all(placement.coverage == _WHOLE for placement in rows.values())


def exact_platform_tags(translation: PlatformTranslation) -> tuple[str, ...]:
    """The ES-DE platform ids exact on the intersection's systems, sorted.

    A declared system whose live ``<platform>`` tag is among these answers
    through that tag even when the table does not know its name — that is what
    the ES-DE platform column is for: a hand-added system's name is unknown to
    the table, its tag is not. A tag that covers more systems than the asked
    pair (``arcade``) names none of them alone, so it is not among these. This
    is the forward question — does the tag cover exactly what was asked, so a
    system carrying it belongs to the asked set — and not
    :func:`names_one_system`'s, which asks which single system a tag names.
    """
    return _intersection_keys(translation, (ESDE_PLATFORM_SOURCE,), (EXACT_MATCH,))
