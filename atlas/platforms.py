"""The other key covers only part of what the asked one does — its vocabulary is finer there."""
RELATED_MATCH: PlatformRelation = "relatedMatch"
"""Neither key contains the other: they overlap (a romset against a system), or each covers part of one system."""

PLATFORM_RELATIONS = (EXACT_MATCH, BROAD_MATCH, NARROW_MATCH, RELATED_MATCH)

