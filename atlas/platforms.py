# The degradations a platform question states — structured, never free-text-only.
# "unmapped": the asked pair is a key its source, a source the table includes,
# does not have (or a system name neither this machine nor the table knows);
# data names what was asked as {source, key}. "source-unknown": the asked pair
# names a source the table does not include (#784 D31); data names the asked
# source and the table's sources, comma-separated.
# "unknown": a catalogue's own <platform> token is outside ES-DE's platform
# ids — the state ES-DE itself warns about and drops (SystemData.cpp at
# v3.5.0); atlas states it. "scraping-ignored": the catalogue tags the system
# `ignore`, ES-DE's opt-out — deliberately no platform, which is a different
# fact than an empty tag. "source-version-differs": the caller named the
# version of the source its key comes from, and the table holds that source at
# another one (#784 D11) — the key may mean something else there.
CAVEAT_PLATFORM_UNMAPPED = "platform-unmapped"
CAVEAT_PLATFORM_SOURCE_UNKNOWN = "platform-source-unknown"
CAVEAT_PLATFORM_UNKNOWN = "platform-unknown"
CAVEAT_PLATFORM_SCRAPING_IGNORED = "platform-scraping-ignored"
CAVEAT_PLATFORM_SOURCE_VERSION_DIFFERS = "platform-source-version-differs"

PlatformRelation = Literal["exactMatch", "broadMatch", "narrowMatch", "relatedMatch"]
PlatformSourceKeyStatus = Literal["keys", "none"]
PlatformPairStatus = Literal["known", "unknown"]
PlatformIntersectionStatus = Literal["agreed", "conflict", "unknown"]

EXACT_MATCH: PlatformRelation = "exactMatch"
"""The other key covers exactly the systems the asked one does."""
BROAD_MATCH: PlatformRelation = "broadMatch"
"""The other key covers the asked one's systems and more — its vocabulary is coarser there."""
NARROW_MATCH: PlatformRelation = "narrowMatch"
"""The other key covers only part of what the asked one does — its vocabulary is finer there."""
RELATED_MATCH: PlatformRelation = "relatedMatch"
"""The two keys overlap without either containing the other (a romset against a system)."""

PLATFORM_RELATIONS = (EXACT_MATCH, BROAD_MATCH, NARROW_MATCH, RELATED_MATCH)

KEYS_FOUND: PlatformSourceKeyStatus = "keys"
"""The source holds keys for the asked systems; ``keys`` lists them."""
KEYS_NONE: PlatformSourceKeyStatus = "none"
"""The source holds no key for any of the asked systems — a definite answer."""

PLATFORM_SOURCE_KEY_STATUSES = (KEYS_FOUND, KEYS_NONE)

PAIR_KNOWN: PlatformPairStatus = "known"
"""The table holds the asked key in the asked source."""
PAIR_UNKNOWN: PlatformPairStatus = "unknown"
"""The table holds no such key, or no such source — a definite answer, not a guess."""

PLATFORM_PAIR_STATUSES = (PAIR_KNOWN, PAIR_UNKNOWN)

INTERSECTION_AGREED: PlatformIntersectionStatus = "agreed"
"""The known pairs share at least one system; ``intersection`` lists every source's keys for them."""
INTERSECTION_CONFLICT: PlatformIntersectionStatus = "conflict"
"""The known pairs share no system; ``conflict`` names them, and atlas picks none (#784 D9)."""
INTERSECTION_UNKNOWN: PlatformIntersectionStatus = "unknown"
"""No asked pair is known, so there is nothing to intersect."""

PLATFORM_INTERSECTION_STATUSES = (INTERSECTION_AGREED, INTERSECTION_CONFLICT, INTERSECTION_UNKNOWN)

# The pseudo-source a bare folder name is asked in (#784 D14): its meaning is
# the union of what every folder vocabulary means by that name.
FOLDER_SOURCE = "folder"
# The two ES-DE columns the machine half reads: the system names a catalogue
# declares, and the platform ids its <platform> tags spell.
ESDE_SOURCE = "esde"
ESDE_PLATFORM_SOURCE = "esde-platform"
FOLDER_SOURCES = (ESDE_SOURCE, "retrodeck", "emudeck", "romm-folder", "batocera", "knulli", "rocknix")

# The kinds a row may carry (#784 D16) — a closed vocabulary, one hyphenated
# word per concept. "unclassified" is the loader's placeholder for a row
# neither a catalogue nor a hand judgement classifies, which the release check
