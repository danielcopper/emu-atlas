# The degradations a platform question states — structured, never free-text-only.
# "unmapped": the asked pair is a key its source, a source the table includes,
# does not have — a bare folder name no folder vocabulary spells, or a system
# name neither this machine nor the table knows, among them; data names what
# was asked as {source, key}. "source-unknown": the asked pair names a source
# the table does not include (#784 D31); data names the asked source and key,
# and the table's sources as a list. "excluded": the source has the key and the
# table places it on no row on purpose (#784 D35); data names {source, key} as
# asked and the reason platform_excluded.json records. Exactly one of these
# three rides every pair that answers unknown.
# "version-unapplied": a bare folder pair stated a version, which names no
# single source, so it was not applied and the union over the folder
# vocabularies stands (#784 D32); data names {source, key, version} as asked.
# "unknown": a catalogue's own <platform> token is outside ES-DE's platform
# ids — the state ES-DE itself warns about and drops (SystemData.cpp at
# v3.5.0); atlas states it. "scraping-ignored": the catalogue tags the system
# `ignore`, ES-DE's opt-out — deliberately no platform, which is a different
# fact than an empty tag. "source-version-differs": the caller named the
# version of the source its key comes from, and none of the projects that
# source's column is read from is pinned at it (#784 D11, D42) — the key may
# mean something else there; data names {source, key, version} as asked and
# `pins`, an object from each project to its pinned version.
# "parts-unestablished": the pairs meet on a row only through different parts
# or overlaps of it — two part keys, two overlap keys, a part and an overlap, a
# part key and a content subset, or two content subsets of one parent — so the
# system is shared but the table cannot know whether those parts or overlaps
# share content (#784 D40); data names the known pairs that meet through a part
# or an overlap, in pair order, as two lists of one length, sources and keys:
# neither a source nor a key is unique among those pairs, so no object could be
# keyed by either, and a pair is the same index in both lists.
CAVEAT_PLATFORM_UNMAPPED = "platform-unmapped"
CAVEAT_PLATFORM_SOURCE_UNKNOWN = "platform-source-unknown"
CAVEAT_PLATFORM_EXCLUDED = "platform-excluded"
CAVEAT_PLATFORM_VERSION_UNAPPLIED = "platform-version-unapplied"
CAVEAT_PLATFORM_UNKNOWN = "platform-unknown"
CAVEAT_PLATFORM_SCRAPING_IGNORED = "platform-scraping-ignored"
CAVEAT_PLATFORM_SOURCE_VERSION_DIFFERS = "platform-source-version-differs"
CAVEAT_PLATFORM_PARTS_UNESTABLISHED = "platform-parts-unestablished"

