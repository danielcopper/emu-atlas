@dataclass(frozen=True, slots=True)
class PlatformKey:
    """One key of one source, as the answer to a pair names it."""

    key: str
    """The source's own key, verbatim — a numeric id as its decimal string."""
    relation: PlatformRelation
    """How this key relates to the asked pair's systems — in the intersection, to the systems
    all known pairs share — one of :data:`PLATFORM_RELATIONS`.
    """
    citations: tuple[str, ...]
    """Where the source states this key's place — file and line (or folder) at the pinned
    revision, a Wikidata statement at its item revision, or a reviewed hand judgement's
    evidence.
    """

    def __post_init__(self) -> None:
        if self.relation not in PLATFORM_RELATIONS:
            raise ValueError(f"PlatformKey: relation {self.relation!r} is not one of {PLATFORM_RELATIONS}")
        if not self.citations:
            raise ValueError(f"PlatformKey {self.key!r}: a key is never stated without a citation")


@dataclass(frozen=True, slots=True)
class PlatformSourceKeys:
    """One source's keys for the systems a pair (or the intersection) names."""

    source: str
    """The source — always one of the table's columns, :func:`known_platform_vocabularies`."""
    status: PlatformSourceKeyStatus
    """``keys`` when the source holds keys for those systems, ``none`` when it holds none —
    one of :data:`PLATFORM_SOURCE_KEY_STATUSES`.
    """
    keys: tuple[PlatformKey, ...]
    """The source's keys, sorted; several keys mean the source is finer there, never that
    atlas is unsure (#784 D8). Empty exactly under ``none``.
    """

    def __post_init__(self) -> None:
        if self.status not in PLATFORM_SOURCE_KEY_STATUSES:
            raise ValueError(f"PlatformSourceKeys: status {self.status!r} is not one of {PLATFORM_SOURCE_KEY_STATUSES}")
        if (self.status == KEYS_FOUND) != bool(self.keys):
            raise ValueError(f"PlatformSourceKeys {self.source!r}: 'keys' lists keys exactly when it is the status")


@dataclass(frozen=True, slots=True)
class PlatformPairAnswer:
    """What one asked ``(source, key)`` pair means in every source."""

    source: str
    """The source the pair was asked in, echoed back as given — a column of the table,
    ``folder``, or any other name, which answers ``unknown``.
    """
    key: str
    """The key the pair was asked with, with surrounding whitespace stripped — the form it is
    matched in.
    """
    version: str | None
    """The source version the caller stated with the pair, or ``None`` when it stated none."""
    status: PlatformPairStatus
    """``known`` or ``unknown``, one of :data:`PLATFORM_PAIR_STATUSES`."""
    sources: tuple[PlatformSourceKeys, ...]
    """Every source's keys for the systems this pair names, in table order; empty when the
    pair is ``unknown``.
    """

    def __post_init__(self) -> None:
        if self.status not in PLATFORM_PAIR_STATUSES:
            raise ValueError(f"PlatformPairAnswer: status {self.status!r} is not one of {PLATFORM_PAIR_STATUSES}")
        if (self.status == PAIR_KNOWN) != bool(self.sources):
            raise ValueError(
                f"PlatformPairAnswer {self.source}/{self.key}: a known pair lists every source, an unknown one none"
            )
        if self.sources and not _any_keys(self.sources):
            raise ValueError(f"PlatformPairAnswer {self.source}/{self.key}: a known pair has a key in some source")


