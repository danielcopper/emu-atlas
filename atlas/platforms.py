"""Platform translation — a ``(source, key)`` pair in, every other source's keys out.

One packaged table maps the keys of every included source onto one another
(DESIGN.md, Vocabulary; issue #784). Which key a frontend, a distribution, a
server product, a core or a registry uses for a system is written nowhere on
the running machine, so it ships here as world knowledge: generated by
``scripts/generate_platform_table.py`` from pinned revisions
(``atlas/data/platform_table.json``), corrected by hand judgements that each
carry a reason and are cited by the keys they anchor on and any further
evidence (``atlas/data/platform_overrides.json``), and
licensed per upstream as ``atlas/data/SOURCES.md`` records.

The table's unit is a *row*: one system at the finest distinction any source
makes. A key maps to a set of rows and covers each of them whole, unless a
reviewed override says it covers only part of a row (``narrowMatch``) or
overlaps it (``relatedMatch``). The relation of another key to the asked one
follows from the row sets and those overrides together, in the SKOS names:
the asked key itself is ``exactMatch``, and so is a key covering the same
systems whole; ``broadMatch`` when the other key wholly covers the asked one
and more, ``narrowMatch`` when the asked key wholly covers the other,
``relatedMatch`` otherwise — an overlap, or two parts of one system. Each
relation is the inverse of the way back. Rows are internal to this module:
their working names appear in no answer, and atlas adds no vocabulary of its
own (#784 D4).

This module owns the world-knowledge half only: the loader and the pure
lookup. Which of the systems a translation names *this installation*
declares lives on the installation handles, because only a handle can say.
"""

